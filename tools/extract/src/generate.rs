fn global(out: &mut Emitter, rep: &mut Report) {
    let gc = out.vfs.exists("data/globalconfig.txt");
    if let Some(p) = gc.and_then(|g| out.parse(&g, rep)) {
        let r = &p.root;
        if let Some(s) = r.child("slowmotion").and_then(|s| s.child("general")) {
            out.begin("slowmotion", "global", rep);
            props(out, s, &[("SlowMotionTime", "slowmotion_time")], &[], "", true);
        }
        out.begin("game", "", rep);
        if let Some(n) = r.child("character") {
            props(out, n, &[], &[], "character_", true);
        }
        if let Some(n) = r.child("projectile") {
            props(out, n, &[], &[], "projectile_", true);
        }
        for (sec, prefix) in [("camera", "camera_"), ("gamemode", "gamemode_"), ("painkiller", "painkiller_")] {
            if let Some(g) = r.child(sec).and_then(|s| s.child("general")) {
                props(out, g, &[], &[], prefix, true);
            }
        }
    } else {
        rep.errors.push("data/globalconfig.txt missing or unparseable".into());
    }
    if let Some(p) = out.vfs.exists("data/difficulty.txt").and_then(|d| out.parse(&d, rep))
        && let Some(d) = p.root.child("difficulty") {
            for level in &d.children {
                for sec in &level.children {
                    if sec.props.is_empty() {
                        continue;
                    }
                    out.begin("difficulty", &format!("{}.{}", level.name.to_ascii_lowercase(), sec.name.to_ascii_lowercase()), rep);
                    props(out, sec, &[], &[], "", true);
                }
            }
        }
    // defaultvalues.txt holds only default key bindings; nothing for gameplay.

    // Gravity is a per-level vector in levels.txt (every retail level uses GRAVITY_VALUE, -20).
    // The character controller integrates it directly, so it is the player's gravity too.
    if let Some(p) = out.vfs.exists("data/database/levels/levels.txt").and_then(|l| out.parse(&l, rep)) {
        let mut nodes = Vec::new();
        p.root.walk(&mut nodes);
        let gravity = nodes.iter().find_map(|n| {
            let v = n.get("Gravity")?;
            v.split_whitespace().nth(1)?.parse::<f32>().ok()
        });
        match gravity {
            Some(g) => {
                out.begin("level", "default", rep);
                out.kv("gravity", &format!("{}", -g));
            }
            None => rep.warnings.push("levels.txt: no Gravity found".into()),
        }
    }
}

