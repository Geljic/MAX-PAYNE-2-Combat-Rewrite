/// Merge the `CHARANIM_` animations under `tree` into `set` by slot name: a later source
/// replaces an earlier one's entry for the same slot, a repeat within one source is a warning.
fn collect_anims<'t>(
    set: &mut Vec<(String, Anim<'t>, &'static str)>,
    tree: &'t Node,
    source: &'static str,
    rep: &mut Report,
) {
    for a in animations(tree) {
        let Some(idx) = a.node.value("Index") else { continue };
        if !idx.raw.to_ascii_uppercase().starts_with("CHARANIM_") {
            continue;
        }
        let name = anim_name(idx);
        match set.iter().position(|e| e.0 == name) {
            Some(i) if set[i].2 == source => {
                rep.warnings.push(format!("duplicate {source} animation {name} at {}", a.node.loc));
            }
            Some(i) => set[i] = (name, a, source),
            None => set.push((name, a, source)),
        }
    }
}


fn character(out: &mut Emitter, rep: &mut Report) {
    let Some(path) = out.vfs.exists(&format!("{DB}/skins/MaxPayne.txt")) else {
        rep.errors.push("skins/MaxPayne.txt not found".into());
        return;
    };
    let Some(p) = out.parse(&path, rep) else { return };
    let root = &p.root;
    let skeleton = root.child("Properties").and_then(|n| n.get("Skeleton")).unwrap_or("male").to_string();
    out.begin("character", "MaxPayne", rep);
    if let Some(pr) = root.child("Properties") {
        props(
            out,
            pr,
            &[
                ("MaximumHealth", "max_health"),
                ("CanShootDodgeFrame", "can_shootdodge_frame"),
                ("CanAbortShootDodgeFrame", "can_abort_shootdodge_frame"),
                ("HighDetailRagdollName", "high_detail_ragdoll"),
                ("LowDetailRagdollName", "low_detail_ragdoll"),
            ],
            &[],
            "",
            false,
        );
    }
    if let Some(ai) = root.child("AI") {
        props(out, ai, &[], &[], "ai_", true);
    }
    for t in root.children_named("Target") {
        let Some(g) = t.child("General") else { continue };
        let bones: Vec<&str> = t.children_named("Bone").filter_map(|b| b.get("Name")).collect();
        out.kv(
            "target",
            &format!(
                "{} | type {} | no_penetration_multiplier {} | full_penetration_multiplier {} | material {} | bones {}",
                g.get("Name").unwrap_or("?"),
                g.get("Type").unwrap_or("?"),
                g.get("NoPenetrationMultiplier").unwrap_or("1"),
                g.get("FullPenetrationMultiplier").unwrap_or("1"),
                g.get("Material").unwrap_or(""),
                bones.join(", ")
            ),
        );
    }
    for blk in ["OnInit", "OnDeath"] {
        if let Some(n) = root.child(blk) {
            for m in n.children_named("Message") {
                if let Some(s) = m.get("String") {
                    let c = out.call(s);
                    out.kv(&format!("{}_msg", snake(blk)), &c);
                }
            }
        }
    }

    // Animations: the skeleton's full default set, with the skin's entries
    // replacing the same index. Files are relative to the skeleton directory.
    let skel_dir = format!("{DB}/skeletons/{skeleton}");
    let bases = vec![skel_dir.clone(), format!("{DB}/skins"), DB.to_string()];
    let skel_parsed = out
        .vfs
        .exists(&format!("{DB}/skeletons/{skeleton}.txt"))
        .and_then(|real| out.parse(&real, rep));

    let mut reverts: Vec<(String, String)> = Vec::new();
    for tree in [skel_parsed.as_ref().map(|p| &p.root), Some(root)].into_iter().flatten() {
        let mut all = Vec::new();
        tree.walk(&mut all);
        for n in &all {
            for r in n.children_named("Revert") {
                if let (Some(f), Some(t)) = (r.value("From"), r.value("To")) {
                    let pair = (anim_name(f), anim_name(t));
                    if !reverts.contains(&pair) {
                        reverts.push(pair);
                    }
                }
            }
        }
    }

    // name -> (animation, source), skeleton order first, skin-only entries last.
    let mut set: Vec<(String, Anim, &'static str)> = Vec::new();
    if let Some(sp) = &skel_parsed {
        collect_anims(&mut set, &sp.root, "skeleton", rep);
    }
    collect_anims(&mut set, root, "skin", rep);
    for (name, a, source) in &set {
        emit_anim(out, rep, "anim", name, a, &bases, Some(*source));
    }
    out.begin("reverts", &skeleton, rep);
    for (f, t) in &reverts {
        out.kv("revert", &format!("{f} {t}"));
    }

    // Sub-animations (face, arms, torso) from the skeleton file, named by their
    // [Reference] so `C_SubAnimate( Sub_X )` calls can find them.
    if let Some(sp) = &skel_parsed {
        let sbases = vec![skel_dir, DB.to_string()];
        for a in animations(&sp.root) {
            let Some(idx) = a.node.value("Index") else { continue };
            if !idx.raw.to_ascii_uppercase().starts_with("SUBANIM_") {
                continue;
            }
            let name = a
                .props
                .and_then(|p| p.child("Reference"))
                .and_then(|r| r.get("Name"))
                .map(str::to_string)
                .unwrap_or_else(|| anim_name(idx));
            emit_anim(out, rep, "subanim", &name, &a, &sbases, None);
        }
    }
}

fn emit_anim(out: &mut Emitter, rep: &mut Report, kind: &str, name: &str, a: &Anim, bases: &[String], source: Option<&str>) {
    out.begin(kind, name, rep);
    if let Some(i) = a.node.get("Index") {
        out.kv("id", i);
    }
    if let Some(f) = a.node.get("Filename") {
        let p = out.asset(bases, f);
        out.kv("file", &p);
    }
    if let Some(pr) = a.props {
        for c in &pr.children {
            match c.name.to_ascii_lowercase().as_str() {
                "movement" => {
                    if let Some(f) = c.get("Filename") {
                        let p = out.asset(bases, f);
                        out.kv("movement", &p);
                    }
                }
                "reference" => {
                    if let Some(n) = c.get("Name") {
                        out.kv("reference", n);
                    }
                }
                "message" => {}
                other => {
                    // Unknown sub-section: keep its numbers so nothing is lost.
                    for (k, v) in &c.props {
                        out.kv(&format!("{other}_{}", snake(k)), &out_val(v));
                    }
                }
            }
        }
        props(out, pr, &[], &[], "", false);
    }
    if let Some(src) = source {
        out.kv("source", src);
    }
    if let Some(pr) = a.props {
        out.messages(pr, "");
    }
}

