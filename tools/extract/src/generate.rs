fn ragdolls(out: &mut Emitter, rep: &mut Report) {
    for f in out.vfs.list(&format!("{DB}/ragdolls"), ".txt") {
        let name = stem(&f).to_string();
        let Some(p) = out.parse(&f, rep) else { continue };
        let bases = vec![format!("{DB}/ragdolls"), format!("{DB}/ragdolls/{name}"), DB.to_string()];
        out.begin("ragdoll", &name, rep);
        if let Some(g) = find(&p.root, "Geometry") {
            if let Some(f) = g.get("ExportData") {
                let file = out.asset(&bases, f);
                out.kv("geometry", &file);
            }
            if let Some(c) = g.get("CrossMode") {
                out.kv("cross_mode", c);
            }
        }
        if let Some(pr) = p.root.child("Properties") {
            props(out, pr, &[], &[], "", false);
        }
        if let Some(pb) = p.root.child("ParticipatingBones") {
            for b in pb.children_named("Bone") {
                let mut s = b.get("Name").unwrap_or("?").to_string();
                for (label, key) in [("weight", "RelativeWeight"), ("restitution", "Restitution"), ("friction", "Friction"), ("inertia", "InertiaTensor")] {
                    if let Some(v) = b.value(key) {
                        let _ = write!(s, " | {label} {}", out_val(v));
                    }
                }
                let known = ["name", "relativeweight", "restitution", "friction", "inertiatensor"];
                for (k, v) in &b.props {
                    if !known.contains(&k.to_ascii_lowercase().as_str()) {
                        let _ = write!(s, " | {} {}", snake(k), out_val(v));
                    }
                }
                out.kv("bone", &s);
            }
        }
        if let Some(j) = p.root.child("Joints") {
            for jn in j.children_named("Joint") {
                let mut s = format!("{} | {}", jn.get("Bone1").unwrap_or("?"), jn.get("Bone2").unwrap_or("?"));
                for (k, v) in &jn.props {
                    if !k.eq_ignore_ascii_case("Bone1") && !k.eq_ignore_ascii_case("Bone2") {
                        let _ = write!(s, " | {} {}", snake(k), out_val(v));
                    }
                }
                out.kv("joint", &s);
            }
        }
        if let Some(r) = p.root.child("BoneRemaps") {
            for rn in r.children_named("Remap") {
                let mut s = rn.get("Bone").unwrap_or("?").to_string();
                for (k, v) in &rn.props {
                    if !k.eq_ignore_ascii_case("Bone") {
                        let _ = write!(s, " | {} {}", snake(k), out_val(v));
                    }
                }
                out.kv("remap", &s);
            }
        }
    }
}

