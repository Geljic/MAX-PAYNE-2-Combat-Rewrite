/// `ai_ranges.h` suffix to `[enemyclass]` key. `HEARINGGROUP*RADIUS` are joined into
/// `hearing_radius` separately.
const CLASS_KEYS: &[(&str, &str)] = &[
    ("MAXIMUMHEALTH", "health"),
    ("AIMINGSPEED", "aiming_speed"),
    ("HEADTURNINGSPEED", "head_turning_speed"),
    ("TRIGGERHAPPINESSANGLE", "trigger_happiness_angle"),
    ("INITIALINACCURACY", "initial_inaccuracy"),
    ("STABLEINACCURACY", "stable_inaccuracy"),
    ("STABILIZATIONTIME", "stabilization_time"),
    ("FIELDOFVISION", "field_of_vision"),
    ("IDLETIMEOUT", "idle_timeout"),
];

/// `#define NAME value` lines of a header, comments dropped.
fn defines(text: &str) -> BTreeMap<String, String> {
    let mut m = BTreeMap::new();
    for line in text.lines() {
        let line = line.split("//").next().unwrap_or("").trim();
        let Some(rest) = line.strip_prefix("#define") else { continue };
        let mut it = rest.split_whitespace();
        if let (Some(k), Some(v)) = (it.next(), it.next()) {
            m.insert(k.to_string(), v.to_string());
        }
    }
    m
}

/// The animation overlay a skin file pulls in: the `Male_*.h` it `#include`s (`SHARP`, `NORMAL`,
/// `NPC`, `PLAYER`), if any. Commented-out includes do not count.
fn overlay_of(skin_text: &str) -> Option<String> {
    for line in skin_text.lines() {
        let l = line.trim();
        if !l.starts_with("#include") {
            continue;
        }
        let l = l.to_ascii_lowercase();
        if let Some(i) = l.find("male_") {
            let name: String = l[i + 5..].chars().take_while(|c| c.is_ascii_alphanumeric()).collect();
            return Some(name.to_ascii_uppercase());
        }
    }
    None
}

/// Leading `C0x` of a class constant or skin name (`C03_AIMINGSPEED`, `C01_Mafioso_A`).
fn class_prefix(s: &str) -> Option<String> {
    let b = s.as_bytes();
    (b.len() > 3 && (b[0] == b'C' || b[0] == b'c') && b[1].is_ascii_digit() && b[2].is_ascii_digit() && b[3] == b'_')
        .then(|| s[..3].to_ascii_uppercase())
}

/// Animation `Male_<style>.h` overlay: every `CHARANIM_` entry as `[anim <STYLE>/<SLOT>]`.
fn overlay_anims(out: &mut Emitter, rep: &mut Report, style: &str, bases: &[String]) {
    let Some(real) = out.vfs.exists(&format!("{DB}/skins/Male_{style}.h")) else {
        rep.warnings.push(format!("skins/Male_{style}.h not found"));
        return;
    };
    let Some(p) = out.parse(&real, rep) else { return };
    let mut set: Vec<(String, Anim, &'static str)> = Vec::new();
    collect_anims(&mut set, &p.root, "overlay", rep);
    for (slot, a, _) in &set {
        let name = format!("{style}/{slot}");
        emit_anim(out, rep, "anim", &name, a, bases, Some(&style.to_ascii_lowercase()));
    }
}

/// Everything the enemy AI needs from the data: per-class numbers, per-skin numbers and which
/// animation overlay a skin uses, plus the overlay clips themselves (`SHARP/`, `NORMAL/`) and the
/// plain enemy base set (`ENEMY/`). See `docs/formats/enemies.md`.
fn enemies(out: &mut Emitter, rep: &mut Report) {
    // Classes.
    if let Some((_, text)) = out.vfs.read(&format!("{DB}/ai_ranges.h")) {
        let d = defines(&text);
        for c in 0..=9 {
            let pre = format!("C{c:02}_");
            let lookup = |k: &str| d.get(&format!("{pre}{k}"));
            let mut lines: Vec<(String, String)> = Vec::new();
            for (suffix, key) in CLASS_KEYS {
                if let Some(v) = lookup(suffix) {
                    lines.push((key.to_string(), v.clone()));
                }
            }
            if let (Some(a), Some(b), Some(c3)) =
                (lookup("HEARINGGROUPONERADIUS"), lookup("HEARINGGROUPTWORADIUS"), lookup("HEARINGGROUPTHREERADIUS"))
            {
                lines.push(("hearing_radius".into(), format!("{a} {b} {c3}")));
            }
            if lines.is_empty() {
                continue;
            }
            out.begin("enemyclass", &format!("C{c:02}"), rep);
            for (k, v) in lines {
                out.kv(&k, &v);
            }
        }
    } else {
        rep.warnings.push("ai_ranges.h not found: no enemy classes".into());
    }

    // Skins: anything with an [AI] section.
    for f in out.vfs.list(&format!("{DB}/skins"), ".txt") {
        let name = stem(&f).to_string();
        let Some((_, text)) = out.vfs.read(&f) else { continue };
        let Some(p) = out.parse(&f, rep) else { continue };
        let Some(ai) = p.root.child("AI") else { continue };
        let pr = p.root.child("Properties");
        let class = ai
            .props
            .iter()
            .find_map(|(_, v)| class_prefix(&v.raw))
            .or_else(|| class_prefix(&name));
        let overlay = overlay_of(&text);
        out.begin("enemyskin", &name, rep);
        match &class {
            Some(c) => out.kv("class", c),
            None => {
                // Hand-tuned skin (for example Enemy_MaxPayne): carry its own numbers.
                let mut hearing = [String::new(), String::new(), String::new()];
                for (k, v) in &ai.props {
                    match k.to_ascii_lowercase().as_str() {
                        "hearinggrouponeradius" => hearing[0] = out_val(v),
                        "hearinggrouptworadius" => hearing[1] = out_val(v),
                        "hearinggroupthreeradius" => hearing[2] = out_val(v),
                        _ => out.kv(&snake(k), &out_val(v)),
                    }
                }
                if hearing.iter().all(|h| !h.is_empty()) {
                    out.kv("hearing_radius", &hearing.join(" "));
                }
            }
        }
        let style = match overlay.as_deref() {
            Some("SHARP") => "SHARP",
            Some("NORMAL") => "NORMAL",
            _ => "",
        };
        out.kv("style", if style.is_empty() { "none" } else { style });
        if let Some(o) = overlay.as_deref().filter(|o| !matches!(*o, "SHARP" | "NORMAL")) {
            out.kv("overlay", &o.to_ascii_lowercase());
        }
        if let Some(pr) = pr {
            for (key, from) in [
                ("capsule_radius", "CapsuleRadius"),
                ("capsule_top", "CapsuleTop"),
                ("slowmo_bonus", "SlowMotionBonusForKiller"),
                ("shooting_frequency_multiplier", "ShootingFrequencyMultiplier"),
                ("airborne_speed", "AirborneSpeed"),
            ] {
                if let Some(v) = pr.value(from) {
                    out.kv(key, &out_val(v));
                }
            }
            if let (Some(a), Some(b)) = (pr.value("CanShootDodgeFrame"), pr.value("CanAbortShootDodgeFrame")) {
                out.kv("shootdodge_frames", &format!("{} {}", out_val(a), out_val(b)));
            }
        }
    }

    // Style overlays, in the skeleton directory's terms like Max's own clips.
    let skeleton = "male";
    let skel_dir = format!("{DB}/skeletons/{skeleton}");
    let bases = vec![skel_dir, format!("{DB}/skins"), DB.to_string()];
    for style in ["SHARP", "NORMAL"] {
        overlay_anims(out, rep, style, &bases);
    }

    // Enemy base set: the skeleton's defaults, for each slot where Max's own skin (with
    // Male_Player.h) replaced them. Max keeps the plain slot name; enemies without an overlay
    // use these defaults, so they go under ENEMY/.
    let skel = out
        .vfs
        .exists(&format!("{DB}/skeletons/{skeleton}.txt"))
        .and_then(|real| out.parse(&real, rep));
    let max = out.vfs.exists(&format!("{DB}/skins/MaxPayne.txt")).and_then(|real| out.parse(&real, rep));
    let (Some(skel), Some(max)) = (skel, max) else { return };
    let mut defaults: Vec<(String, Anim, &'static str)> = Vec::new();
    collect_anims(&mut defaults, &skel.root, "skeleton", rep);
    let mut maxset: Vec<(String, Anim, &'static str)> = Vec::new();
    collect_anims(&mut maxset, &max.root, "skin", rep);
    let resolve = |out: &mut Emitter, a: &Anim| -> (String, String) {
        let file = a.node.get("Filename").map(|f| out.asset(&bases, f)).unwrap_or_default();
        let mov = a
            .props
            .and_then(|p| p.child("Movement"))
            .and_then(|m| m.get("Filename"))
            .map(|f| out.asset(&bases, f))
            .unwrap_or_default();
        (file, mov)
    };
    for (slot, a, _) in &defaults {
        let Some((_, m, _)) = maxset.iter().find(|e| &e.0 == slot) else { continue };
        if resolve(out, a) != resolve(out, m) {
            emit_anim(out, rep, "anim", &format!("ENEMY/{slot}"), a, &bases, Some("enemy"));
        }
    }
}

