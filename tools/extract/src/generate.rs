const WEAPON_RENAMES: &[(&str, &str)] = &[
    ("Clipsize", "clip_size"),
    ("Pocketsize", "pocket_size"),
    ("DefaultShootingFrequency", "shooting_frequency"),
    ("ShootingFrequencyMultiplier", "slowmo_multiplier"),
    ("ShootDodgeAllowed", "shootdodge_allowed"),
    ("BulletProjectileOffset", "bullet_offset"),
    ("EmptyShellProjectileOffset", "empty_shell_offset"),
    ("ClipProjectileOffset", "clip_offset"),
    ("SlotIndex", "slot"),
    ("InventoryID", "inventory_id"),
    ("WeaponID", "weapon_id"),
];

fn weapons(out: &mut Emitter, rep: &mut Report) {
    let files = out.vfs.list(&format!("{DB}/weapons"), ".txt");
    for f in files {
        let name = stem(&f).to_string();
        let Some(p) = out.parse(&f, rep) else { continue };
        let bases = vec![format!("{DB}/weapons/{name}"), format!("{DB}/weapons"), DB.to_string()];
        out.begin("weapon", &name, rep);
        for lod in p.root.children_named("LOD") {
            if let Some(g) = lod.child("Geometry") {
                let file = g.get("ExportData").map(|f| out.asset(&bases, f)).unwrap_or_default();
                out.kv("geometry", &format!("{file} | distance {}", g.get("Distance").unwrap_or("0")));
            }
        }
        let anims = animations(&p.root);
        // The player projectile: the one the PLAYERSHOOT animation creates.
        let mut proj = None;
        let mut referenced = Vec::new();
        for a in &anims {
            let Some(pr) = a.props else { continue };
            let is_player = a.node.value("Index").is_some_and(|i| i.raw.to_ascii_uppercase().ends_with("PLAYERSHOOT"));
            for m in pr.children_named("Message") {
                if let Some(n) = created_projectile(m.get("String").unwrap_or("")) {
                    if is_player && proj.is_none() && n.to_ascii_lowercase().contains("player") {
                        proj = Some(n.clone());
                    }
                    referenced.push(n);
                }
            }
        }
        // Weapon attributes, then the bullet's numbers copied up for convenience.
        let attrs = p.root.child("Attributes");
        if let Some(a) = attrs {
            props(out, a, WEAPON_RENAMES, &[], "", false);
        }
        if let Some(pn) = &proj {
            out.kv("projectile", pn);
            let ppath = format!("{DB}/projectiles/{pn}.txt");
            if let Some(real) = out.vfs.exists(&ppath)
                && let Some(pp) = out.parse(&real, rep)
                    && let Some(pa) = pp.root.child("Attributes") {
                        for (key, from) in [("damage", "Damage"), ("penetration", "PenetrationValue"), ("bullet_spread", "Accuracy"), ("bullet_speed", "Speed")] {
                            if let Some(v) = pa.value(from) {
                                out.kv(key, &out_val(v));
                            }
                        }
                    }
        } else {
            rep.warnings.push(format!("weapon {name}: no player projectile found"));
        }
        for a in &anims {
            let Some(idx) = a.node.value("Index") else { continue };
            let an = anim_name(idx);
            let file = a.node.get("Filename").map(|f| out.asset(&bases, f)).unwrap_or_default();
            out.kv("anim", &format!("{an} {} {file}", idx.text));
            if let Some(pr) = a.props {
                out.messages(pr, &an);
            }
        }
        out.pending.extend(referenced);
    }
}

/// `this->P_CreateProjectile ( Name, 1 )` and variants: the projectile name.
fn created_projectile(msg: &str) -> Option<String> {
    let l = msg.to_ascii_lowercase();
    let i = l.find("p_createprojectile")?;
    let open = msg[i..].find('(')? + i;
    let rest = &msg[open + 1..];
    let end = rest.find([',', ')'])?;
    let n = rest[..end].trim();
    (!n.is_empty()).then(|| n.to_string())
}

fn projectiles(out: &mut Emitter, rep: &mut Report) {
    let mut queue: VecDeque<String> = std::mem::take(&mut out.pending);
    let mut done = BTreeSet::new();
    while let Some(name) = queue.pop_front() {
        if !done.insert(name.to_ascii_lowercase()) {
            continue;
        }
        let path = format!("{DB}/projectiles/{name}.txt");
        let Some(real) = out.vfs.exists(&path) else {
            rep.warnings.push(format!("projectile {name} referenced but has no file"));
            continue;
        };
        let Some(p) = out.parse(&real, rep) else { continue };
        let stem_name = stem(&real).to_string();
        let bases = vec![format!("{DB}/projectiles/{stem_name}"), format!("{DB}/projectiles"), DB.to_string()];
        out.begin("projectile", &stem_name, rep);
        for lod in p.root.children_named("LOD") {
            if let Some(g) = lod.child("Geometry")
                && let Some(f) = g.get("ExportData") {
                    let file = out.asset(&bases, f);
                    out.kv("geometry", &file);
                }
        }
        if let Some(a) = p.root.child("Attributes") {
            props(out, a, &[("GravityMultiplier", "gravity")], &[], "", false);
        }
        for n in &p.root.children {
            if n.name.eq_ignore_ascii_case("Attributes") || n.props.is_empty() {
                continue;
            }
            if let Some(s) = n.get("String") {
                let c = out.call(s);
                out.kv(&format!("on_{}", snake(&n.name)), &c);
                if let Some(c) = created_projectile(s) {
                    queue.push_back(c);
                }
            }
        }
        for a in animations(&p.root) {
            let Some(idx) = a.node.value("Index") else { continue };
            let an = anim_name(idx);
            if let Some(pr) = a.props {
                out.messages(pr, &an);
                for m in pr.children_named("Message") {
                    if let Some(c) = created_projectile(m.get("String").unwrap_or("")) {
                        queue.push_back(c);
                    }
                }
            }
        }
    }
}

