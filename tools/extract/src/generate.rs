//! Emits `payne.data`, the runtime data file `payne` loads, from Max Payne 2's
//! text database (see `database.rs` for the parser, `docs/formats/database.md`
//! for what each emitted key means).
//!
//! The output is plain text, one `[kind name]` header per record followed by
//! `key = value` lines. Keys may repeat and order is preserved. Values are
//! normalised: booleans are `true`/`false`, tuples are space-separated,
//! percentages are fractions (`7%` is `0.07`).

use crate::database::{self as db, Node, Parsed, Source, Value, Vfs, normalize_path};
use std::collections::{BTreeMap, BTreeSet, HashMap, VecDeque};
use std::fmt::Write as _;
use std::fs;
use std::io;
use std::path::Path;

/// What a [`generate`] run did and what it could not resolve.
#[derive(Debug, Default)]
pub struct Report {
    /// Records written per kind (character, anim, weapon, ...).
    pub counts: BTreeMap<String, usize>,
    /// Hard problems: files that failed to parse. A clean run has none.
    pub errors: Vec<String>,
    /// UPPER_CASE constants no `#define` covered, with use counts.
    pub unresolved_macros: BTreeMap<String, u32>,
    /// Files named by the database (includes, animations, geometry) that
    /// exist in no archive.
    pub missing_files: Vec<String>,
    pub warnings: Vec<String>,
    /// Same virtual path with different content in two archives.
    pub conflicts: Vec<String>,
}

impl Report {
    pub fn summary(&self) -> String {
        let mut s = String::new();
        for (k, n) in &self.counts {
            let _ = writeln!(s, "{k}: {n}");
        }
        let _ = writeln!(
            s,
            "errors {}, unresolved macros {}, missing files {}, warnings {}, conflicts {}",
            self.errors.len(),
            self.unresolved_macros.len(),
            self.missing_files.len(),
            self.warnings.len(),
            self.conflicts.len()
        );
        s
    }
}

const DB: &str = "data/database";

/// Read the merged tree under `mp2_files`, write `out_file`.
pub fn generate(mp2_files: &Path, out_file: &Path) -> io::Result<Report> {
    let vfs = Vfs::scan(mp2_files)?;
    let mut report = Report { conflicts: vfs.conflicts.clone(), ..Default::default() };
    let text = build(&vfs, &mut report);
    if let Some(dir) = out_file.parent() {
        fs::create_dir_all(dir)?;
    }
    fs::write(out_file, text)?;
    Ok(report)
}

/// Build the whole file text from any [`Source`] plus a directory lister.
fn build(vfs: &Vfs, rep: &mut Report) -> String {
    let mut out = Emitter::new(vfs);
    out.buf.push_str("# generated by payne-extract from your own Max Payne 2 files; do not commit\n");
    let r = &mut *rep;
    character(&mut out, r);
    enemies(&mut out, r);
    weapons(&mut out, r);
    ragdolls(&mut out, r);
    projectiles(&mut out, r);
    global(&mut out, r);
    rep.missing_files.extend(out.missing.iter().cloned());
    rep.missing_files.sort();
    rep.missing_files.dedup();
    out.buf
}

// ---------------------------------------------------------------------------
// Emitter helpers
// ---------------------------------------------------------------------------

struct Emitter<'a> {
    vfs: &'a dyn Lister,
    buf: String,
    /// lowercase function name to the first casing seen, so the same call
    /// always prints the same way (the game ignores case, the loader need not).
    canon: HashMap<String, String>,
    missing: BTreeSet<String>,
    /// Projectile names the weapons reference, emitted after the weapons.
    pending: VecDeque<String>,
}

/// What the emitter needs beyond [`Source`]: directory listings.
trait Lister: Source {
    fn list(&self, dir: &str, ext: &str) -> Vec<String>;
}
impl Lister for Vfs {
    fn list(&self, dir: &str, ext: &str) -> Vec<String> {
        Vfs::list(self, dir, ext)
    }
}

impl<'a> Emitter<'a> {
    fn new(vfs: &'a dyn Lister) -> Self {
        Emitter { vfs, buf: String::new(), canon: HashMap::new(), missing: BTreeSet::new(), pending: VecDeque::new() }
    }

    fn begin(&mut self, kind: &str, name: &str, rep: &mut Report) {
        if name.is_empty() {
            let _ = writeln!(self.buf, "\n[{kind}]");
        } else {
            let _ = writeln!(self.buf, "\n[{kind} {name}]");
        }
        *rep.counts.entry(kind.to_string()).or_insert(0) += 1;
    }

    fn kv(&mut self, k: &str, v: &str) {
        let _ = writeln!(self.buf, "{k} = {v}");
    }

    /// Parse a database file, folding diagnostics into the report.
    fn parse(&self, virt: &str, rep: &mut Report) -> Option<Parsed> {
        match db::parse(self.vfs, virt) {
            Ok(p) => {
                for m in &p.missing_includes {
                    rep.missing_files.push(format!("include {m}"));
                }
                for (k, n) in &p.unresolved {
                    *rep.unresolved_macros.entry(k.clone()).or_insert(0) += n;
                }
                Some(p)
            }
            Err(e) => {
                rep.errors.push(e.to_string());
                None
            }
        }
    }

    /// Resolve an asset path written in a database file to the real-cased
    /// path under `data/database/`. Tries each base directory in order; the
    /// first hit wins. Unknown files are recorded as missing and returned
    /// normalised against the first base.
    fn asset(&mut self, bases: &[String], rel: &str) -> String {
        let rel = rel.replace('\\', "/");
        for b in bases {
            let cand = normalize_path(&format!("{b}/{rel}"));
            if let Some(real) = self.vfs.exists(&cand) {
                return strip_db(&real);
            }
        }
        let first = normalize_path(&format!("{}/{}", bases[0], rel));
        self.missing.insert(strip_db(&first));
        strip_db(&first)
    }

    /// `this->Func( a, b )` becomes `this.Func a b`. Quoted arguments keep
    /// their quotes so a reader can still split on spaces.
    fn call(&mut self, s: &str) -> String {
        let s = s.trim().trim_end_matches(';').trim();
        let Some((recv, rest)) = s.split_once("->") else { return s.to_string() };
        let recv = recv.trim();
        let lower = recv.to_ascii_lowercase();
        let recv = if lower == "this" {
            "this".to_string()
        } else {
            let r = lower.strip_prefix("maxpayne_").unwrap_or(&lower);
            let mut c = r.chars();
            match c.next() {
                Some(f) => f.to_ascii_uppercase().to_string() + c.as_str(),
                None => String::new(),
            }
        };
        let (func, args) = match rest.find('(') {
            Some(i) => {
                let end = rest.rfind(')').unwrap_or(rest.len());
                (rest[..i].trim(), split_args(&rest[i + 1..end.max(i + 1)]))
            }
            None => (rest.trim(), vec![]),
        };
        let func = self.canon.entry(func.to_ascii_lowercase()).or_insert_with(|| func.to_string()).clone();
        let mut o = format!("{recv}.{func}");
        for a in args {
            o.push(' ');
            o.push_str(&a);
        }
        o
    }

    /// Emit `msg = [prefix] frame call` for each `[Message]` child.
    fn messages(&mut self, props: &Node, prefix: &str) {
        for m in props.children_named("Message") {
            let Some(s) = m.get("String") else { continue };
            let frame = m.get("Frame").unwrap_or("0");
            let call = self.call(s);
            if prefix.is_empty() {
                self.kv("msg", &format!("{frame} {call}"));
            } else {
                self.kv("msg", &format!("{prefix} {frame} {call}"));
            }
        }
    }
}

fn strip_db(p: &str) -> String {
    p.strip_prefix("data/database/").unwrap_or(p).to_string()
}

fn split_args(s: &str) -> Vec<String> {
    let mut out = Vec::new();
    let (mut cur, mut inq, mut depth) = (String::new(), false, 0);
    for ch in s.chars() {
        match ch {
            '"' => {
                inq = !inq;
                cur.push(ch);
            }
            '(' if !inq => {
                depth += 1;
                cur.push(ch);
            }
            ')' if !inq => {
                depth -= 1;
                cur.push(ch);
            }
            ',' if !inq && depth == 0 => {
                out.push(cur.trim().to_string());
                cur.clear();
            }
            _ => cur.push(ch),
        }
    }
    if !cur.trim().is_empty() || !out.is_empty() {
        out.push(cur.trim().to_string());
    }
    out
}

/// `CamelCase` to `snake_case`, keeping acronym runs together.
pub fn snake(s: &str) -> String {
    let c: Vec<char> = s.chars().collect();
    let mut o = String::new();
    for (i, &ch) in c.iter().enumerate() {
        if ch.is_ascii_uppercase() && i > 0 {
            let prev = c[i - 1];
            let next_lower = c.get(i + 1).is_some_and(|n| n.is_ascii_lowercase());
            if prev.is_ascii_lowercase() || prev.is_ascii_digit() || (prev.is_ascii_uppercase() && next_lower) {
                o.push('_');
            }
        }
        o.push(ch.to_ascii_lowercase());
    }
    o
}

/// Normalised output form of a value (see module docs).
pub fn out_val(v: &Value) -> String {
    let t = v.text.trim();
    if let Some(p) = t.strip_suffix('%')
        && let Ok(x) = p.trim().parse::<f64>() {
            return format!("{}", ((x / 100.0) * 1e9).round() / 1e9);
        }
    match t.to_ascii_lowercase().as_str() {
        "yes" | "true" => "true".into(),
        "no" | "false" => "false".into(),
        _ => t.to_string(),
    }
}

/// True for values made only of numbers and booleans (what `[game]` keeps).
fn is_plain(v: &Value) -> bool {
    let t = v.text.trim();
    !t.is_empty()
        && t.split_whitespace()
            .all(|w| db::parse_number(w).is_some() || v_bool(w))
}
fn v_bool(w: &str) -> bool {
    matches!(w.to_ascii_lowercase().as_str(), "yes" | "no" | "true" | "false")
}

/// Emit every property of `n` as snake_case, except keys in `skip`
/// (lowercase), with `rename` overrides applied first.
fn props(out: &mut Emitter, n: &Node, rename: &[(&str, &str)], skip: &[&str], prefix: &str, plain_only: bool) {
    for (k, v) in &n.props {
        let lk = k.to_ascii_lowercase();
        if skip.contains(&lk.as_str()) || (plain_only && !is_plain(v)) {
            continue;
        }
        let key = rename
            .iter()
            .find(|(a, _)| a.eq_ignore_ascii_case(k))
            .map(|(_, b)| b.to_string())
            .unwrap_or_else(|| snake(k));
        out.kv(&format!("{prefix}{key}"), &out_val(v));
    }
}

fn stem(virt: &str) -> &str {
    let f = virt.rsplit('/').next().unwrap_or(virt);
    f.rsplit_once('.').map(|x| x.0).unwrap_or(f)
}

fn find<'a>(root: &'a Node, name: &str) -> Option<&'a Node> {
    let mut all = Vec::new();
    root.walk(&mut all);
    all.into_iter().find(|n| n.name.eq_ignore_ascii_case(name))
}

// ---------------------------------------------------------------------------
// Animations (shared by skins, weapons, projectiles)
// ---------------------------------------------------------------------------

struct Anim<'a> {
    node: &'a Node,
    props: Option<&'a Node>,
}

/// Every `[Animation]` under `root` with the `[Properties]` that directly
/// follows it. (When several animations precede one `[Properties]` it binds
/// to the last, which is how the projectile files read.)
fn animations(root: &Node) -> Vec<Anim<'_>> {
    let mut all = Vec::new();
    root.walk(&mut all);
    let mut v = Vec::new();
    for n in all {
        for (i, c) in n.children.iter().enumerate() {
            if c.name.eq_ignore_ascii_case("Animation") {
                let props = n.children.get(i + 1).filter(|p| p.name.eq_ignore_ascii_case("Properties"));
                v.push(Anim { node: c, props });
            }
        }
    }
    v
}

/// Index name without its `XXXANIM_` prefix: `CHARANIM_RUNFORWARD` is `RUNFORWARD`.
fn anim_name(v: &Value) -> String {
    let raw = v.raw.trim();
    raw.split_once('_').map(|x| x.1).unwrap_or(raw).to_string()
}

